-- Expose only this extension's installed version to its own runtime role.
create function garmin.native_schema_version() returns integer
language plpgsql security definer set search_path = '' as $$
begin
 if session_user <> 'brain_ext_garmin' then
   raise exception 'extension role required' using errcode = '42501';
 end if;
 return (select pg_catalog.max(m.version) from brain.schema_migrations m where m.owner = 'garmin');
end $$;
revoke all on function garmin.native_schema_version() from public;
grant execute on function garmin.native_schema_version() to brain_ext_garmin;

