-- Forward-only adaptation of the pinned SQLite migrations 0001-0016.
-- Connection is always paired with its owner; integer values retain SQLite's 64-bit range.
-- SQLite uses integer arithmetic until an operation overflows int64, then
-- evaluates that operation (and subsequent ones) in IEEE binary64. Compare
-- the final REAL to an integer without rounding the integer cutoff to REAL.
create function garmin.activity_ends_before_cutoff(start_ms bigint, duration_s bigint, cutoff bigint)
returns boolean language plpgsql immutable strict parallel safe as $$
declare
 product numeric := duration_s::numeric * 1000;
 total numeric;
 real_total double precision;
begin
 if product between -9223372036854775808::numeric and 9223372036854775807::numeric then
  total := start_ms::numeric + product;
  if total between -9223372036854775808::numeric and 9223372036854775807::numeric then
   return total < cutoff::numeric;
  end if;
  real_total := start_ms::double precision + product::bigint::double precision;
 else
  real_total := start_ms::double precision + (duration_s::double precision * 1000::double precision);
 end if;
 if real_total < '-9223372036854775808'::double precision then
  return true;
 elsif real_total >= '9223372036854775808'::double precision then
  return false;
 end if;
 return floor(real_total)::bigint < cutoff;
end $$;
revoke all on function garmin.activity_ends_before_cutoff(bigint,bigint,bigint) from public;
grant execute on function garmin.activity_ends_before_cutoff(bigint,bigint,bigint) to brain_ext_garmin;

