#!/usr/bin/env python3
"""Opt-in: generate the frozen fixture using the archived, isolated v8 implementation."""
import json
import os
from pathlib import Path
import subprocess
import sys
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parents[3]
ARCHIVE = ROOT / '_bmad-output/personal-brain/prep-garmin-absorption/inputs/garmin-source.tar.gz'
FIXTURE = ROOT / 'extensions/garmin/tests/fixtures/normalize_v8'
DIGEST_FIXTURE = ROOT / 'extensions/garmin/tests/fixtures/digest_v8'

CHILD = r'''
import json, sqlite3, sys
from garmin_pipeline import normalize, store
fixture = json.loads(open(sys.argv[1], encoding="utf-8").read())
conn = sqlite3.connect(":memory:", autocommit=True)
store._migrate(conn, store._load_migrations())
for item in fixture["items"]:
    conn.execute("INSERT INTO raw_response(scope,key,endpoint,raw,fetched_at,checked_at,library_version) VALUES (?,?,?,?,?,?,?)", (item["scope"],item["key"],item["endpoint"],item["raw"],item["fetched_at"],item["fetched_at"],"synthetic"))
if fixture.get("history_start"):
    conn.execute("INSERT INTO meta(key,value) VALUES ('history_start',?)", (fixture["history_start"],))
normalize.run(conn,rebuild=True,timezone=fixture["timezone"])
out = {}
for table in normalize._DERIVED_TABLES:
    columns = [r[1] for r in conn.execute("PRAGMA table_info(" + table + ")") if r[1] != "normalized_at"]
    rows = [dict(zip(columns,row)) for row in conn.execute("SELECT " + ",".join(columns) + " FROM " + table)]
    out[table] = sorted(rows, key=lambda row: json.dumps(row,sort_keys=True,ensure_ascii=False))
print(json.dumps(out,ensure_ascii=False,sort_keys=True,indent=2))
'''

DIGEST_CHILD = r'''
import json, sys
from garmin_pipeline import digest
data = json.loads(open(sys.argv[1], encoding='utf-8').read())
def build(d): return digest.build(d['manifest'], d['days'], d['activities'], d['labels'], d['body'])
out = build(data) if 'manifest' in data else {name:build(case) for name,case in data.items()}
print(json.dumps(out, ensure_ascii=False, sort_keys=True, indent=2, allow_nan=False))
'''

DAY_CHILD = r'''
import json, sys
from garmin_pipeline import digest
d = json.loads(open(sys.argv[1], encoding="utf-8").read())
print(json.dumps(digest.day_values(d['date'],d['day_raw'],d['activities'],d['labels'],d['timezone']),ensure_ascii=False,sort_keys=True,indent=2,allow_nan=False))
'''

CHART_CHILD = r'''
import json, sys
from pathlib import Path
from datetime import date
import chart_db
from garmin_pipeline import config, charts, store, body
root = Path(sys.argv[1]).resolve()
(root / 'config.toml').write_text('environment = "dev"\ntokenstore = "tokens"\n')
cfg = config.load(root / 'config.toml')
chart_db.synthetic(cfg)
# The fixture sidecars are generated by chart_db itself and are valid.
body.read_sidecar = lambda schema, path, day: json.loads(path.read_text())
with store.read_connection(cfg) as conn:
    rows = conn.execute("select scope,key,endpoint,raw,fetched_at from raw_response order by scope,key,endpoint").fetchall()
    history = conn.execute("select value from meta where key='history_start'").fetchone()[0]
raw = [dict(zip(('scope','key','endpoint','raw','fetched_at'),row)) for row in rows]
data = charts._read_chart_data(cfg, date.fromisoformat(chart_db.REPORT_DATE))
print(json.dumps({'snapshot':{'raw':raw,'history_start':history},'measurements':data['body_measurements']['items'],'report_date':chart_db.REPORT_DATE,'timezone':'Asia/Seoul','expected':data},ensure_ascii=False,sort_keys=True,indent=2,allow_nan=False))
'''

def main():
    with tempfile.TemporaryDirectory(prefix='garmin-oracle-') as temporary:
        temp = Path(temporary)
        with tarfile.open(ARCHIVE, 'r:gz') as archive:
            archive.extractall(temp, filter='data')
        source = temp / 'garmin-source' / 'src'
        home = temp / 'home'
        home.mkdir()
        env = {'HOME': str(home), 'PYTHONPATH': str(source), 'PATH': os.defpath}
        result = subprocess.run([sys.executable, '-c', CHILD, str(FIXTURE / 'input.json')], cwd=temp, env=env, text=True, capture_output=True, check=True)
        (FIXTURE / 'expected.json').write_text(result.stdout, encoding='utf-8')
        for prefix in ('', 'edge_', 'cases_'):
            result = subprocess.run([sys.executable, '-c', DIGEST_CHILD, str(DIGEST_FIXTURE / (prefix + 'input.json'))], cwd=temp, env=env, text=True, capture_output=True, check=True)
            (DIGEST_FIXTURE / (prefix + 'expected.json')).write_text(result.stdout, encoding='utf-8')
        env['PYTHONPATH'] = str(source) + os.pathsep + str(temp / 'garmin-source' / 'tests')
        chart_dir = ROOT / 'extensions/garmin/tests/fixtures/charts_v8'
        chart_dir.mkdir(exist_ok=True)
        result = subprocess.run([sys.executable, '-c', CHART_CHILD, str(temp)], cwd=temp, env=env, text=True, stdout=subprocess.PIPE, check=True)
        (chart_dir / 'synthetic.json').write_text(result.stdout, encoding='utf-8')
        result = subprocess.run([sys.executable, '-c', DAY_CHILD, str(DIGEST_FIXTURE / 'core_current_input.json')], cwd=temp, env=env, text=True, capture_output=True, check=True)
        (DIGEST_FIXTURE / 'core_current_expected.json').write_text(result.stdout, encoding='utf-8')

if __name__ == '__main__':
    main()
